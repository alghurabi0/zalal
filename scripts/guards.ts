// Guard rules from CLAUDE.md that ESLint can't express (docs/claude-code-setup.md §3.3).
// Runs from `pnpm lint`, so CI and Claude Code both hit it.
//
//   node scripts/guards.ts            check every file in scope
//   node scripts/guards.ts <file>...  check only these files (the edit hook uses this)
//
// To allow one exception, put a comment on the line or the line above:
//   guard-allow <rule>[, <rule>]: <reason>
// The reason is required.

import { readdirSync, readFileSync } from "node:fs";
import { extname, isAbsolute, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export type RuleId =
  | "no-physical-direction"
  | "no-raw-color"
  | "no-arbitrary-value"
  | "no-arabic"
  | "rls-enabled"
  | "definer-search-path"
  | "guard-allow-reason";

export type Violation = { file: string; line: number; rule: RuleId; message: string };

const RULES = new Set<string>([
  "no-physical-direction",
  "no-raw-color",
  "no-arbitrary-value",
  "no-arabic",
  "rls-enabled",
  "definer-search-path",
]);

// Theme tokens, SVG illustrations, and the manifest colors that a unit test keeps
// equal to the tokens (tests/unit/brand.test.ts).
const RAW_COLOR_ALLOWED = [
  "src/app/globals.css",
  "src/components/illustrations/",
  "src/lib/brand.ts",
];
// Generated by `pnpm db:types`.
const GENERATED = ["src/lib/database.types.ts"];

const SOURCE_EXT = new Set([".ts", ".tsx", ".mts", ".js", ".jsx", ".mjs"]);

/** Which rule set applies to a repo-relative path, or null if it's out of scope. */
export function scopeOf(file: string): "source" | "css" | "sql" | null {
  if (GENERATED.includes(file)) return null;
  if (file.startsWith("src/")) {
    const ext = extname(file);
    if (SOURCE_EXT.has(ext)) return "source";
    if (ext === ".css") return "css";
    return null;
  }
  if (/^supabase\/migrations\/[^/]+\.sql$/.test(file)) return "sql";
  return null;
}

export function checkFile(file: string, text: string): Violation[] {
  const scope = scopeOf(file);
  if (!scope) return [];
  const found: Violation[] = [];
  const add = (line: number, rule: RuleId, message: string) =>
    found.push({ file, line, rule, message });

  if (scope === "sql") {
    checkSql(text, add);
  } else {
    const code = scope === "source" ? blankJsComments(text) : blankCssComments(text);
    const lines = code.split("\n");
    const rawColorAllowed = RAW_COLOR_ALLOWED.some((p) => file === p || file.startsWith(p));
    lines.forEach((line, i) => {
      const n = i + 1;
      checkDirection(line, scope, (m) => add(n, "no-physical-direction", m));
      if (!rawColorAllowed) checkRawColor(line, (m) => add(n, "no-raw-color", m));
      if (scope === "source") {
        checkArbitrary(line, (m) => add(n, "no-arbitrary-value", m));
        if (/\p{Script=Arabic}/u.test(line)) {
          add(n, "no-arabic", "Arabic text belongs in messages/ar.json (read it with next-intl)");
        }
      }
    });
  }

  return applyAllows(file, text, found);
}

// --- Class tokens -----------------------------------------------------------

/** Class-like tokens on a line. Strings are split on whitespace and quotes. */
function tokens(line: string): string[] {
  return line.split(/[\s"'`{},;]+/).filter(Boolean);
}

/** Splits `md:data-[state=open]:-ml-2!` into variants and the utility `ml-2`. */
export function utilityOf(token: string): { variants: string[]; utility: string } {
  const parts: string[] = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < token.length; i++) {
    const c = token[i];
    if (c === "[" || c === "(") depth++;
    else if ((c === "]" || c === ")") && depth > 0) depth--;
    else if (c === ":" && depth === 0) {
      parts.push(token.slice(start, i));
      start = i + 1;
    }
  }
  const last = token.slice(start);
  const utility = last.replace(/^!/, "").replace(/!$/, "").replace(/^-/, "");
  return { variants: parts, utility };
}

// Physical-direction utilities and their logical replacements.
const PHYSICAL_PREFIX = /^(?:m[lr]|p[lr]|scroll-m[lr]|scroll-p[lr]|left|right)-/;
const PHYSICAL_EXACT =
  /^(?:rounded-(?:[lr]|tl|tr|bl|br)|border-[lr]|text-(?:left|right)|float-(?:left|right)|clear-(?:left|right))(?:-|$)/;
const PHYSICAL_POSITION =
  /^(?:origin|object|bg)-(?:(?:top|bottom)-)?(?:left|right)(?:-(?:top|bottom))?$/;

const LOGICAL_HINT = "use ms-/me-/ps-/pe-/start-/end-/text-start/text-end/rounded-s/rounded-e";

// CSS properties, in stylesheets and in inline-style strings.
const CSS_PHYSICAL =
  /(?<![\w-])(?:(?:margin|padding|border|scroll-margin|scroll-padding)-(?:left|right)|border-(?:top|bottom)-(?:left|right)-radius)(?![\w-])|(?<![\w-])(?:text-align|float|clear)\s*:\s*(?:left|right)\b/;
const CSS_LEFT_RIGHT = /(?<![\w-])(?:left|right)\s*:/;
// Inline style objects in TSX.
const STYLE_PHYSICAL =
  /\b(?:margin|padding|border|scrollMargin|scrollPadding)(?:Left|Right)\b|\bborder(?:Top|Bottom)(?:Left|Right)Radius\b|\b(?:textAlign|float|clear)\s*:\s*["'](?:left|right)["']/;

function checkDirection(line: string, scope: "source" | "css", report: (m: string) => void) {
  for (const token of tokens(line)) {
    const { utility } = utilityOf(token);
    if (
      PHYSICAL_PREFIX.test(utility) ||
      PHYSICAL_EXACT.test(utility) ||
      PHYSICAL_POSITION.test(utility)
    ) {
      report(`"${token}" is a left/right class; ${LOGICAL_HINT}`);
    }
  }
  const css = CSS_PHYSICAL.exec(line) ?? (scope === "css" ? CSS_LEFT_RIGHT.exec(line) : null);
  if (css) report(`"${css[0].trim()}" is a left/right property; use the -inline-start/-end form`);
  if (scope === "source") {
    const style = STYLE_PHYSICAL.exec(line);
    if (style) report(`"${style[0]}" is a left/right style; use the Inline Start/End form`);
  }
}

function checkArbitrary(line: string, report: (m: string) => void) {
  for (const token of tokens(line)) {
    const { utility } = utilityOf(token);
    // `bg-[#fff]`, `rounded-[13px]`, `bg-(--x)`, `[mask-type:alpha]`. Arbitrary
    // variants such as `data-[state=open]:` are fine.
    if (/^[a-z][\w-]*-[[(]/.test(utility) || /^\[[a-z-]+:[^\]]+\]$/.test(utility)) {
      report(`"${token}" is an arbitrary value; add a token to @theme in globals.css instead`);
    }
  }
}

const HEX = /(?<![\w&])#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})(?![\w-])/i;
const COLOR_FN = /\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch)\(/i;

function checkRawColor(line: string, report: (m: string) => void) {
  const m = HEX.exec(line) ?? COLOR_FN.exec(line);
  if (m) report(`"${m[0]}" is a raw color; use a color token from globals.css`);
}

// --- SQL --------------------------------------------------------------------

const IDENT = String.raw`(?:"[^"]+"|[A-Za-z_][\w$]*)`;
const QUALIFIED = String.raw`(${IDENT}(?:\s*\.\s*${IDENT})?)`;

/** `Public."Orders"` → `public.Orders`; unqualified names are in `public`. */
function normalizeName(name: string): string {
  const parts = name
    .split(/\s*\.\s*/)
    .map((p) => (p.startsWith('"') ? p.slice(1, -1) : p.toLowerCase()));
  return parts.length === 1 ? `public.${parts[0]}` : parts.join(".");
}

function checkSql(text: string, add: (line: number, rule: RuleId, message: string) => void) {
  const code = blankSqlComments(text);
  const lineAt = (offset: number) => text.slice(0, offset).split("\n").length;

  // Every table gets RLS in the same migration.
  const enabled = new Set<string>();
  const enableRe = new RegExp(
    String.raw`\balter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?${QUALIFIED}\s+enable\s+row\s+level\s+security\b`,
    "gi",
  );
  for (const m of code.matchAll(enableRe)) enabled.add(normalizeName(m[1]!));
  const createRe = new RegExp(
    String.raw`\bcreate\s+(?:unlogged\s+)?table\s+(?:if\s+not\s+exists\s+)?${QUALIFIED}`,
    "gi",
  );
  for (const m of code.matchAll(createRe)) {
    const name = normalizeName(m[1]!);
    if (!enabled.has(name)) {
      add(
        lineAt(m.index),
        "rls-enabled",
        `table ${name} needs "alter table ${name} enable row level security;" in this migration`,
      );
    }
  }

  // Every security definer function pins its search_path.
  for (const stmt of sqlStatements(code)) {
    const head = blankDollarBodies(stmt.text);
    if (!/^\s*create\s+(?:or\s+replace\s+)?(?:function|procedure)\b/i.test(head)) continue;
    if (!/\bsecurity\s+definer\b/i.test(head)) continue;
    if (/\bset\s+search_path\s*(?:=|to)\s*''/i.test(head)) continue;
    const name = /(?:function|procedure)\s+([^\s(]+)/i.exec(head)?.[1] ?? "function";
    add(
      lineAt(stmt.offset + (stmt.text.length - stmt.text.trimStart().length)),
      "definer-search-path",
      `security definer ${name} needs "set search_path = ''" (and fully qualified names inside)`,
    );
  }
}

/** Top-level statements, split on `;` outside strings, identifiers and dollar quotes. */
function sqlStatements(code: string): { text: string; offset: number }[] {
  const out: { text: string; offset: number }[] = [];
  let start = 0;
  let i = 0;
  while (i < code.length) {
    const c = code[i];
    if (c === "'" || c === '"') {
      const end = code.indexOf(c, i + 1);
      i = end === -1 ? code.length : end + 1;
      continue;
    }
    if (c === "$") {
      const tag = /^\$[A-Za-z_]*\$/.exec(code.slice(i))?.[0];
      if (tag) {
        const end = code.indexOf(tag, i + tag.length);
        i = end === -1 ? code.length : end + tag.length;
        continue;
      }
    }
    if (c === ";") {
      out.push({ text: code.slice(start, i), offset: start });
      start = i + 1;
    }
    i++;
  }
  if (code.slice(start).trim()) out.push({ text: code.slice(start), offset: start });
  return out;
}

function blankDollarBodies(stmt: string): string {
  return stmt.replace(/(\$[A-Za-z_]*\$)[\s\S]*?\1/g, (m) => m.replace(/[^\n]/g, " "));
}

// --- Comment blanking (keeps offsets and line numbers) -----------------------

const blank = (s: string) => s.replace(/[^\n]/g, " ");

function blankJsComments(text: string): string {
  let out = "";
  let i = 0;
  while (i < text.length) {
    const c = text[i]!;
    const next = text[i + 1];
    if (c === "/" && next === "/") {
      const end = text.indexOf("\n", i);
      const stop = end === -1 ? text.length : end;
      out += blank(text.slice(i, stop));
      i = stop;
    } else if (c === "/" && next === "*") {
      const end = text.indexOf("*/", i + 2);
      const stop = end === -1 ? text.length : end + 2;
      out += blank(text.slice(i, stop));
      i = stop;
    } else if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < text.length && text[j] !== c) j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j + 1;
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

function blankCssComments(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, blank);
}

function blankSqlComments(text: string): string {
  let out = "";
  let i = 0;
  while (i < text.length) {
    const c = text[i]!;
    if (c === "-" && text[i + 1] === "-") {
      const end = text.indexOf("\n", i);
      const stop = end === -1 ? text.length : end;
      out += blank(text.slice(i, stop));
      i = stop;
    } else if (c === "/" && text[i + 1] === "*") {
      const end = text.indexOf("*/", i + 2);
      const stop = end === -1 ? text.length : end + 2;
      out += blank(text.slice(i, stop));
      i = stop;
    } else if (c === "'") {
      const end = text.indexOf("'", i + 1);
      const stop = end === -1 ? text.length : end + 1;
      out += text.slice(i, stop);
      i = stop;
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

// --- guard-allow ------------------------------------------------------------

const ALLOW = /guard-allow\b\s*([\w-]+(?:\s*,\s*[\w-]+)*)?\s*(?::\s*(.*\S))?/;

function applyAllows(file: string, text: string, found: Violation[]): Violation[] {
  const lines = text.split("\n");
  const allowed = new Map<number, Set<string>>();
  const extra: Violation[] = [];
  lines.forEach((line, i) => {
    const m = ALLOW.exec(line);
    if (!m) return;
    const rules = (m[1] ?? "").split(/\s*,\s*/).filter(Boolean);
    const unknown = rules.filter((r) => !RULES.has(r));
    if (!rules.length || unknown.length || !m[2]) {
      extra.push({
        file,
        line: i + 1,
        rule: "guard-allow-reason",
        message: `write "guard-allow <rule>: <reason>" with a known rule (${[...RULES].join(", ")})`,
      });
      return;
    }
    for (const n of [i + 1, i + 2]) {
      const set = allowed.get(n) ?? new Set<string>();
      rules.forEach((r) => set.add(r));
      allowed.set(n, set);
    }
  });
  const kept = found.filter((v) => !allowed.get(v.line)?.has(v.rule));
  return [...kept, ...extra].sort((a, b) => a.line - b.line);
}

// --- CLI --------------------------------------------------------------------

const ROOT = fileURLToPath(new URL("..", import.meta.url));

function listFiles(dir: string): string[] {
  try {
    return readdirSync(resolve(ROOT, dir), { recursive: true, withFileTypes: true })
      .filter((d) => d.isFile())
      .map((d) => relative(ROOT, resolve(d.parentPath, d.name)).split("\\").join("/"));
  } catch {
    return [];
  }
}

export function run(args: string[]): Violation[] {
  const files = args.length
    ? args.map((a) =>
        relative(ROOT, isAbsolute(a) ? a : resolve(process.cwd(), a))
          .split("\\")
          .join("/"),
      )
    : [...listFiles("src"), ...listFiles("supabase/migrations")];
  return files
    .filter((f) => scopeOf(f))
    .flatMap((f) => {
      try {
        return checkFile(f, readFileSync(resolve(ROOT, f), "utf8"));
      } catch {
        return []; // deleted or unreadable: nothing to check
      }
    });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const violations = run(process.argv.slice(2));
  for (const v of violations) console.error(`${v.file}:${v.line}  ${v.rule}  ${v.message}`);
  if (violations.length) {
    console.error(`\n${violations.length} guard problem(s). Rules: CLAUDE.md, scripts/guards.ts.`);
    process.exit(1);
  }
}
